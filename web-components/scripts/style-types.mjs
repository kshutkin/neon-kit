import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileStyle, createStyleDeclaration } from '@neon-kit/style-build';

const source = resolve(import.meta.dirname, '../src');
const theme = dirname(fileURLToPath(import.meta.resolve('@neon-kit/theme/package.json')));
const declarations = new Map();
for (const name of await readdir(source)) {
    if (/\.(js|jsx)$/.test(name)) {
        const text = await readFile(resolve(source, name), 'utf8');
        for (const [ , specifier] of text.matchAll(/from ['"](@neon-kit\/theme\/[^'"]+\.css\?neon[^'"]*)['"]/g)) {
            const [file, query] = specifier.split('?');
            const graph = await compileStyle(resolve(theme, file.slice('@neon-kit/theme/'.length)), {
                read: (path) => readFile(path, 'utf8'),
                resolve: async (dependency, importer) => resolve(dirname(importer), dependency),
            }, { hostExport: new URLSearchParams(query).get('host') ?? undefined });
            declarations.set(specifier, createStyleDeclaration(specifier, graph.at(-1)));
        }
    }
}
await writeFile(resolve(source, 'styles.d.ts'), '// Generated by scripts/style-types.mjs.\n' + [...declarations.values()].join('\n'));
